import "server-only";
import { clientEnv } from "@/lib/env/client";
import { serverEnv } from "@/lib/env/server";

/**
 * Server-side calls to the Firebase Auth REST API (Identity Toolkit). Signing
 * in on the server lets merchant sign-in resolve usernames, count failures
 * and lock accounts before any password reaches Firebase from the browser,
 * and lets registration mint a session in the same request.
 */

/** Firebase Auth error codes we map to friendly copy. */
export type IdentityErrorCode =
  | "INVALID_LOGIN_CREDENTIALS"
  | "USER_DISABLED"
  | "TOO_MANY_ATTEMPTS_TRY_LATER"
  | "INVALID_OOB_CODE"
  | "EXPIRED_OOB_CODE"
  | "WEAK_PASSWORD"
  | "UNKNOWN";

/** A failed Identity Toolkit call, with its normalised error code. */
export class IdentityError extends Error {
  constructor(public readonly code: IdentityErrorCode) {
    super(`Identity Toolkit error: ${code}`);
    this.name = "IdentityError";
  }
}

const KNOWN: ReadonlySet<string> = new Set([
  "INVALID_LOGIN_CREDENTIALS",
  "USER_DISABLED",
  "TOO_MANY_ATTEMPTS_TRY_LATER",
  "INVALID_OOB_CODE",
  "EXPIRED_OOB_CODE",
  "WEAK_PASSWORD",
]);

function normaliseCode(message: string | undefined): IdentityErrorCode {
  const code = (message ?? "").split(":")[0]?.trim() ?? "";
  // Older projects report these separately; both mean "wrong email or password".
  if (code === "EMAIL_NOT_FOUND" || code === "INVALID_PASSWORD") return "INVALID_LOGIN_CREDENTIALS";
  return KNOWN.has(code) ? (code as IdentityErrorCode) : "UNKNOWN";
}

function baseUrl(): string {
  const emulator = serverEnv.FIREBASE_AUTH_EMULATOR_HOST;
  return emulator && serverEnv.USE_FIREBASE_EMULATORS
    ? `http://${emulator}/identitytoolkit.googleapis.com/v1`
    : "https://identitytoolkit.googleapis.com/v1";
}

async function call<T>(endpoint: string, body: Record<string, unknown>): Promise<T> {
  const response = await fetch(
    `${baseUrl()}/${endpoint}?key=${encodeURIComponent(clientEnv.NEXT_PUBLIC_FIREBASE_API_KEY)}`,
    {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify(body),
      cache: "no-store",
    },
  );
  const json = (await response.json().catch(() => ({}))) as T & { error?: { message?: string } };
  if (!response.ok || json.error) throw new IdentityError(normaliseCode(json.error?.message));
  return json;
}

/** Checks an email and password; returns a fresh ID token (with current claims). */
export async function signInWithPassword(
  email: string,
  password: string,
): Promise<{ idToken: string; uid: string }> {
  const result = await call<{ idToken: string; localId: string }>("accounts:signInWithPassword", {
    email,
    password,
    returnSecureToken: true,
  });
  return { idToken: result.idToken, uid: result.localId };
}

/** Exchanges an Admin SDK custom token for an ID token (used after a role upgrade). */
export async function signInWithCustomToken(token: string): Promise<{ idToken: string }> {
  const result = await call<{ idToken: string }>("accounts:signInWithCustomToken", {
    token,
    returnSecureToken: true,
  });
  return { idToken: result.idToken };
}

/** Applies an email verification code; returns the verified email. */
export async function applyEmailVerification(oobCode: string): Promise<{ email: string }> {
  const result = await call<{ email: string; emailVerified?: boolean }>("accounts:update", {
    oobCode,
  });
  return { email: result.email };
}

/** Checks a password reset code without using it; returns the account email. */
export async function verifyPasswordResetCode(oobCode: string): Promise<{ email: string }> {
  const result = await call<{ email: string }>("accounts:resetPassword", { oobCode });
  return { email: result.email };
}

/** Sets a new password with a reset code; returns the account email. */
export async function confirmPasswordReset(
  oobCode: string,
  newPassword: string,
): Promise<{ email: string }> {
  const result = await call<{ email: string }>("accounts:resetPassword", { oobCode, newPassword });
  return { email: result.email };
}

/** Pulls the one-time code out of a link generated by the Admin SDK. */
export function oobCodeFromLink(link: string): string {
  const code = new URL(link).searchParams.get("oobCode");
  if (!code) throw new Error("Generated action link has no oobCode");
  return code;
}
