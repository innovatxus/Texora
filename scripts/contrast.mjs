// Computes WCAG 2.2 contrast ratios for ATELIER token pairs and writes
// docs/CONTRAST.md. Run with `npm run contrast`; CI runs it with --check.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
const tokensCss = readFileSync(new URL("src/styles/tokens.css", root), "utf8");

const tokens = Object.fromEntries(
  [...tokensCss.matchAll(/--color-([a-z-]+):\s*(#[0-9a-f]{6})/gi)].map((m) => [
    m[1],
    m[2].toLowerCase(),
  ]),
);

function luminance(hex) {
  const channels = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const [r, g, b] = channels.map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function ratio(fg, bg) {
  const [hi, lo] = [luminance(fg), luminance(bg)].sort((a, b) => b - a);
  return (hi + 0.05) / (lo + 0.05);
}

// [foreground, background, usage, required ratio]
// 4.5 = normal text (AA), 3 = large text / UI component boundaries (AA).
const pairs = [
  ["ink", "canvas", "Body text on page", 4.5],
  ["brand", "canvas", "Logo on page", 4.5],
  ["brand", "surface", "Logo on cards", 4.5],
  ["brand", "surface-muted", "Logo in footer", 4.5],
  ["brand", "brand-tint", "Green text on hover tint", 4.5],
  ["surface", "brand", "Text on green buttons", 4.5],
  ["surface", "brand-strong", "Text on pressed green buttons", 4.5],
  ["ink", "surface", "Body text on cards/drawers", 4.5],
  ["ink", "surface-muted", "Text on chips/placeholders", 4.5],
  ["ink-soft", "canvas", "Secondary text on page", 4.5],
  ["ink-soft", "surface", "Secondary text on cards", 4.5],
  ["ink-soft", "surface-muted", "Secondary text on chips", 4.5],
  ["ink-subtle", "canvas", "Meta/captions on page", 4.5],
  ["ink-subtle", "surface", "Meta/captions on cards", 4.5],
  ["ink-subtle", "surface-muted", "Meta on chips", 4.5],
  ["surface", "ink", "Primary button label", 4.5],
  ["canvas", "ink", "Inverse text (announcement bar)", 4.5],
  ["accent", "canvas", "Accent links/loyalty on page", 4.5],
  ["accent", "surface", "Accent links on cards", 4.5],
  ["sale", "canvas", "Sale price on page", 4.5],
  ["sale", "surface", "Sale price on cards", 4.5],
  ["success", "canvas", "Success message", 4.5],
  ["success", "surface", "Success message on cards", 4.5],
  ["warning", "canvas", "Warning message", 4.5],
  ["warning", "surface", "Warning message on cards", 4.5],
  ["focus", "canvas", "Focus ring (non-text)", 3],
  ["focus", "surface", "Focus ring on cards (non-text)", 3],
  ["line-strong", "canvas", "Selected swatch/size outline", 3],
  ["ink-subtle", "canvas", "Input border alternative (non-text)", 3],
];

const rows = pairs.map(([fg, bg, usage, required]) => {
  if (!tokens[fg] || !tokens[bg]) throw new Error(`Missing token: ${fg} or ${bg}`);
  const value = ratio(tokens[fg], tokens[bg]);
  return { fg, bg, usage, required, value, pass: value >= required };
});

const failures = rows.filter((r) => !r.pass);

const table = rows
  .map(
    (r) =>
      `| \`${r.fg}\` ${tokens[r.fg]} | \`${r.bg}\` ${tokens[r.bg]} | ${r.usage} | ${r.value.toFixed(2)}:1 | ${r.required}:1 | ${r.pass ? "Pass" : "**Fail**"} |`,
  )
  .join("\n");

const markdown = `# Contrast ratios — ATELIER tokens

Generated by \`npm run contrast\` from \`src/styles/tokens.css\` (WCAG 2.2 relative-luminance formula).
Do not edit by hand. CI fails if any pair drops below its requirement.

Requirement: 4.5:1 for normal text (SC 1.4.3), 3:1 for non-text UI such as focus rings and selected outlines (SC 1.4.11).

| Foreground | Background | Usage | Ratio | Required | Result |
|---|---|---|---|---|---|
${table}

## Rules that follow from this table

- \`line\` (${tokens.line}) is a decorative hairline only. It must never be the sole boundary of an interactive control; inputs pair it with a \`line-strong\` focus/hover state and a visible label.
- \`accent\` is AA for text, so it may be used for link hover and loyalty copy.
- \`ink-subtle\` is the lightest colour permitted for any text.
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(new URL("docs/CONTRAST.md", root), "utf8");
  if (current !== markdown) {
    console.error("docs/CONTRAST.md is out of date. Run `npm run contrast`.");
    process.exit(1);
  }
} else {
  writeFileSync(fileURLToPath(new URL("docs/CONTRAST.md", root)), markdown);
}

for (const r of rows) {
  console.log(`${r.pass ? "PASS" : "FAIL"} ${r.value.toFixed(2)}  ${r.fg} on ${r.bg}`);
}
if (failures.length > 0) process.exit(1);
